-- Optional bootstrap for an EMPTY Oracle 12c+ schema. Do not run against existing tables.
CREATE TABLE sap_dobavljaci (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    sifra VARCHAR2(20) NOT NULL UNIQUE,
    naziv VARCHAR2(200) NOT NULL,
    web_portal VARCHAR2(4000)
);

COMMENT ON COLUMN sap_dobavljaci.web_portal IS 'Web portal dobavljača';

CREATE TABLE sap_ugovori (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    godina VARCHAR2(4),
    br_ugovor VARCHAR2(10) NOT NULL,
    ugovor_dms VARCHAR2(100),
    jn VARCHAR2(20),
    br_poz_plana VARCHAR2(20),
    predmet_ugovora VARCHAR2(300),
    id_sap_dobavljac NUMBER(10) REFERENCES sap_dobavljaci(id),
    otvoren_ug VARCHAR2(10),
    zzn VARCHAR2(10),
    pocetak_ug DATE,
    kraj_ug DATE,
    vrednost_ug NUMBER(15,2),
    valuta_ug VARCHAR2(10),
    kurs_ug NUMBER(9,5),
    kom_grupa VARCHAR2(5),
    m_br_komerc VARCHAR2(20),
    naz_komerc VARCHAR2(40),
    gr_nab VARCHAR2(5),
    naziv_gr_plan VARCHAR2(40),
    vrs_pred VARCHAR2(400)
);

CREATE UNIQUE INDEX sap_ugovori_uk ON sap_ugovori (br_ugovor, br_poz_plana);

CREATE TABLE sap_odglica (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    id_sap_ugovori NUMBER(10) NOT NULL REFERENCES sap_ugovori(id),
    odg_zap VARCHAR2(8) NOT NULL,
    naziv_odg_zap VARCHAR2(100) NOT NULL,
    r_br NUMBER(10) NOT NULL
);

CREATE TABLE ugo_org (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    sifra VARCHAR2(10) NOT NULL UNIQUE,
    sifra_cir VARCHAR2(10),
