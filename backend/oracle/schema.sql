CREATE TABLE ugo_kor_role (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    id_ugo_kor NUMBER(10) NOT NULL REFERENCES ugo_kor(id),
    id_ugo_org NUMBER(10) NOT NULL REFERENCES ugo_org(id),
    status CHAR(1),
    datpri TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    datizm TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE ugo_dob_lica (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    id_sap_dobavljac NUMBER(10) NOT NULL REFERENCES sap_dobavljaci(id),
    id_ugo_org NUMBER(10) NOT NULL REFERENCES ugo_org(id),
