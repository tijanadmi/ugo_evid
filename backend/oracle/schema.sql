    naziv_cir VARCHAR2(200),
    status CHAR(1),
    datpri TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    datizm TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE ugo_dob_lica_role (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    naziv VARCHAR2(100) NOT NULL,
    status CHAR(1),
    datpri TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    datzm TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE ugo_kor (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ad_sifra VARCHAR2(200) NOT NULL UNIQUE,
    sifra VARCHAR2(200) NOT NULL UNIQUE,
    lozinka VARCHAR2(200) NOT NULL UNIQUE,
    ime VARCHAR2(100),
    status CHAR(1),
    datpri TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    datizm TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
