CREATE TABLE ugo_evid (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    id_sap_ugovor NUMBER(10) NOT NULL REFERENCES sap_ugovori(id),
    id_ugo_org NUMBER(10) NOT NULL REFERENCES ugo_org(id),
    ime VARCHAR2(100) NOT NULL,
    telefon VARCHAR2(100),
    email VARCHAR2(100),
    status CHAR(1),
    datpri TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    datizm TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    id_ugo_dob_lica NUMBER(10) REFERENCES ugo_dob_lica(id),
    UNIQUE (id_sap_ugovor, id_ugo_org)
);
CREATE OR REPLACE VIEW sap_ugovori_v AS
SELECT 
    u.id AS ugovor_id,
    u.godina,
    u.br_ugovor,
    u.ugovor_dms,
    u.jn,
    u.br_poz_plana,
    u.predmet_ugovora,
    u.otvoren_ug,
    u.pocetak_ug,
    u.kraj_ug,
    u.naz_komerc,
    u.gr_nab,
    u.naziv_gr_plan,
    u.vrs_pred,
    d.naziv AS dob_naziv,
    d.web_portal AS dob_web,
    -- r_br = 1
    MAX(CASE WHEN o.r_br = 1 THEN o.odg_zap END)        AS odg_zap_1,
    MAX(CASE WHEN o.r_br = 1 THEN o.naziv_odg_zap END)  AS odg_naziv_1,
    -- r_br = 2
    MAX(CASE WHEN o.r_br = 2 THEN o.odg_zap END)        AS odg_zap_2,
    MAX(CASE WHEN o.r_br = 2 THEN o.naziv_odg_zap END)  AS odg_naziv_2,
    -- r_br = 3
    MAX(CASE WHEN o.r_br = 3 THEN o.odg_zap END)        AS odg_zap_3,
    MAX(CASE WHEN o.r_br = 3 THEN o.naziv_odg_zap END)  AS odg_naziv_3,
    -- r_br = 4
    MAX(CASE WHEN o.r_br = 4 THEN o.odg_zap END)        AS odg_zap_4,
    MAX(CASE WHEN o.r_br = 4 THEN o.naziv_odg_zap END)  AS odg_naziv_4
FROM sap_ugovori u
LEFT JOIN sap_dobavljaci d 
    ON d.id = u.id_sap_dobavljac
LEFT JOIN sap_odglica o 
    ON o.id_sap_ugovori = u.id
GROUP BY 
    u.id, u.godina, u.br_ugovor, u.ugovor_dms, u.jn, u.br_poz_plana,
    u.predmet_ugovora, u.otvoren_ug, u.pocetak_ug, u.kraj_ug, 
    u.naz_komerc, u.gr_nab, u.naziv_gr_plan, u.vrs_pred,
    d.naziv, d.web_portal
ORDER BY u.id;
