CREATE TABLE TED.UGO_DOC_TEMPLATE (
 ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 ID_UGO_EVID INTEGER NOT NULL REFERENCES TED.UGO_EVID(ID),
 ID_TIP_DOC INTEGER NOT NULL REFERENCES TED.UGO_TIP_DOC(ID),
 VERZIJA NUMBER(10) NOT NULL,
 ORIGINALNI_NAZIV VARCHAR2(255 CHAR) NOT NULL,
 PUTANJA VARCHAR2(1000 BYTE) NOT NULL,
 ID_KORISNIKA INTEGER NOT NULL,
 DATPRI TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT UQ_DOC_TEMPLATE_VER UNIQUE(ID_UGO_EVID,ID_TIP_DOC,VERZIJA)
);
CREATE TABLE TED.UGO_TEH_IZVESTAJ (
 ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 ID_UGO_EVID INTEGER NOT NULL REFERENCES TED.UGO_EVID(ID),
 ID_TEH_PERIOD INTEGER NOT NULL REFERENCES TED.UGO_TEH_PERIOD(ID),
 ID_TEMPLATE NUMBER(19) NOT NULL REFERENCES TED.UGO_DOC_TEMPLATE(ID),
 BROJ_KVARTALA NUMBER(4,0) NOT NULL CHECK(BROJ_KVARTALA BETWEEN 1 AND 9999),
 PERIOD_OD DATE NOT NULL,
 PERIOD_DO DATE NOT NULL,
 DATUM_POTPISA DATE NOT NULL,
 DOCX_PUTANJA VARCHAR2(1000 BYTE) NOT NULL,
 PDF_PUTANJA VARCHAR2(1000 BYTE),
 ID_KORISNIKA INTEGER NOT NULL,
 DATPRI TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX TED.IX_TEH_IZVESTAJ_PERIOD ON TED.UGO_TEH_IZVESTAJ(ID_UGO_EVID,ID_TEH_PERIOD,ID);
COMMIT;
