  ORIGINALNI_NAZIV     VARCHAR2(255 CHAR)       NOT NULL,
  PUTANJA              VARCHAR2(500 CHAR)       NOT NULL,
  MIME_TIP             VARCHAR2(150 CHAR)       NOT NULL,
  VELICINA_BAJT        NUMBER(19)               NOT NULL,
  SHA256               VARCHAR2(64 CHAR)        NOT NULL,
