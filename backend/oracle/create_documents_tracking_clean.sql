-- FRESH installation of these SIX tables only. Oracle 12c+; run as TED in script mode.
-- NOT a repair/migration script for existing tables. No data is dropped.
-- Requires UGO_EVID, UGO_TIP_DOC, UGO_KOR with enabled single-column ID PK/UK.
-- Uses TED default tablespace. Identity starts at 1; not a data-import script.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF

DECLARE
 n NUMBER;
BEGIN
 IF USER <> 'TED' THEN
  RAISE_APPLICATION_ERROR(-20001, 'Connect as TED.');
 END IF;
 FOR t IN (SELECT column_value name FROM TABLE(sys.odcivarchar2list(
  'UGO_DOC','UGO_RAZ_ZAHTEV','UGO_TEH_PERIOD','UGO_ODRZAVANJE',
  'UGO_RAZ_FOND','UGO_RAZ_VRSTA_RADA'))) LOOP
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_name=t.name;
  IF n>0 THEN
   RAISE_APPLICATION_ERROR(-20002, 'Object already exists: '||t.name||'. Inspect existing schema; do not drop data.');
  END IF;
 END LOOP;
 FOR t IN (SELECT column_value name FROM TABLE(sys.odcivarchar2list(
  'UGO_EVID','UGO_TIP_DOC','UGO_KOR'))) LOOP
  SELECT COUNT(*) INTO n FROM user_constraints c
   WHERE c.table_name=t.name AND c.constraint_type IN ('P','U') AND c.status='ENABLED'
   AND (SELECT COUNT(*) FROM user_cons_columns cc WHERE cc.constraint_name=c.constraint_name)=1
   AND EXISTS (SELECT 1 FROM user_cons_columns cc WHERE cc.constraint_name=c.constraint_name AND cc.column_name='ID');
  IF n=0 THEN
   RAISE_APPLICATION_ERROR(-20003, 'Missing parent ID key: '||t.name);
  END IF;
 END LOOP;
END;
/

