CREATE TABLE TED.UGO_DOC
(
  ID                   NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_UGO_EVID          NUMBER(10)               NOT NULL,
  ID_TIP_DOC           NUMBER(10)               NOT NULL,
  NAZIV                VARCHAR2(200 CHAR)       NOT NULL,
