CREATE TABLE TED.UGO_RAZ_ZAHTEV
(
  ID                 NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_RAZ_FONDA       NUMBER(10)                 NOT NULL,
  BROJ_ZAHTEVA       VARCHAR2(100 CHAR)         NOT NULL,
  DATUM_ZAHTEVA      DATE                       NOT NULL,
  BROJ_CASOVA        NUMBER(10)                 NOT NULL,
  ROK_RADNIH_DANA    NUMBER(5)                  NOT NULL,
  ROK_POTPISA        DATE                       NOT NULL,
  DATUM_POTPISA      DATE,
  STATUS             VARCHAR2(20 CHAR)          DEFAULT 'NACRT'               NOT NULL,
  NAPOMENA           VARCHAR2(2000 CHAR),
  VERSION            NUMBER(19)                 DEFAULT 1                     NOT NULL,
  ID_KORISNIKA       NUMBER(10)                 NOT NULL,
  DATPRI             TIMESTAMP(6)               DEFAULT SYSTIMESTAMP          NOT NULL,
  DATIZM             TIMESTAMP(6),
  DATUM_REALIZACIJE  DATE
);

COMMENT ON COLUMN TED.UGO_RAZ_ZAHTEV.ROK_POTPISA IS 'Snapshot calculated using approved work calendar; counting starts the day after request date. Service completion is due on or before this date; signature may follow.';

COMMENT ON COLUMN TED.UGO_RAZ_ZAHTEV.STATUS IS 'NACRT/OTKAZAN/OBRISAN do not consume hours; all other statuses reserve or consume hours.';

COMMENT ON COLUMN TED.UGO_RAZ_ZAHTEV.DATUM_REALIZACIJE IS 'Actual service completion date; independent of signature date. Legacy unknown dates remain NULL.';

CREATE INDEX TED.IX_RAZ_FOND_ZAHTEV ON TED.UGO_RAZ_ZAHTEV
(ID_RAZ_FONDA, STATUS);

CREATE INDEX TED.IX_RAZ_PODSETNIK ON TED.UGO_RAZ_ZAHTEV
(STATUS, ROK_POTPISA);

ALTER TABLE TED.UGO_RAZ_ZAHTEV ADD (
  CONSTRAINT CK_RAZ_DATUMI
  CHECK (DATUM_ZAHTEVA=TRUNC(DATUM_ZAHTEVA) AND ROK_POTPISA>DATUM_ZAHTEVA)
  ENABLE VALIDATE,
  CONSTRAINT CK_RAZ_POTPIS
  CHECK (STATUS<>'ZAVRSEN' OR DATUM_POTPISA IS NOT NULL)
  ENABLE VALIDATE,
  CONSTRAINT CK_RAZ_REALIZACIJA
  CHECK (
DATUM_REALIZACIJE IS NULL OR
(DATUM_REALIZACIJE=TRUNC(DATUM_REALIZACIJE) AND DATUM_REALIZACIJE>=DATUM_ZAHTEVA
AND (DATUM_POTPISA IS NULL OR DATUM_REALIZACIJE<=DATUM_POTPISA)))
  ENABLE VALIDATE,
  CONSTRAINT CK_RAZ_ROK_POTPISA
  CHECK ((DATUM_POTPISA IS NULL OR DATUM_POTPISA>=DATUM_ZAHTEVA) AND (DATUM_REALIZACIJE IS NULL OR DATUM_REALIZACIJE<=ROK_POTPISA))
  ENABLE VALIDATE,
  CONSTRAINT CK_RAZ_STATUS
  CHECK (STATUS IN ('NACRT','PODNET','U_RADU','NA_POTPISU','ZAVRSEN','OTKAZAN','OBRISAN'))
  ENABLE VALIDATE,
  CHECK (BROJ_CASOVA BETWEEN 1 AND 2147483647)
  ENABLE VALIDATE,
  CHECK (ROK_RADNIH_DANA BETWEEN 1 AND 3660)
  ENABLE VALIDATE,
  CHECK (VERSION>0)
  ENABLE VALIDATE,
  PRIMARY KEY
  (ID)
  ENABLE VALIDATE);

