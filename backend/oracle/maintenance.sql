-- Old contracts may remain unclassified; every new insert must specify a type.
CREATE OR REPLACE TRIGGER TED.TRG_EVID_TIP_REQUIRED
BEFORE INSERT ON TED.UGO_EVID FOR EACH ROW
BEGIN
 IF :NEW.ID_TIP_UGOVORA IS NULL THEN
  RAISE_APPLICATION_ERROR(-20001,'Tip ugovora je obavezan.');
 END IF;
END;
/
MERGE INTO TED.UGO_TIP_DOC t USING (
 SELECT 'POTVRDA_TEH' SIFRA, 'Potvrda o tehničkoj podršci' NAZIV FROM DUAL
 UNION ALL SELECT 'ZAPISNIK_TEH', 'Zapisnik o tehničkoj podršci' FROM DUAL
) s ON (t.SIFRA=s.SIFRA)
WHEN NOT MATCHED THEN INSERT(SIFRA,NAZIV,REDOSLED) VALUES(s.SIFRA,s.NAZIV,50);
CREATE TABLE TED.UGO_ODRZAVANJE (
 ID NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 ID_UGO_EVID NUMBER(10,0) NOT NULL UNIQUE REFERENCES TED.UGO_EVID(ID),
 DATUM_POTPISA DATE NOT NULL, DATUM_KRAJA DATE NOT NULL,
 IMA_RAZVOJNU_PODRSKU NUMBER(1,0) DEFAULT 0 NOT NULL CHECK (IMA_RAZVOJNU_PODRSKU IN (0,1)),
 TEH_PERIOD_MESECI NUMBER(3,0),
 ID_TEH_TIP_DOC NUMBER(10,0) NOT NULL REFERENCES TED.UGO_TIP_DOC(ID),
 TEH_PODSETNIK_DANA NUMBER(3,0) DEFAULT 7 NOT NULL,
 RAZ_PODSETNIK_DANA NUMBER(3,0) DEFAULT 3 NOT NULL,
 VERSION NUMBER(19,0) DEFAULT 1 NOT NULL,
 ID_KORISNIKA_UNOSA NUMBER(10,0) NOT NULL REFERENCES TED.UGO_KOR(ID),
 DATPRI TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT CK_ODR_DATUM CHECK (DATUM_KRAJA>=DATUM_POTPISA),
 CONSTRAINT CK_ODR_PERIOD CHECK (TEH_PERIOD_MESECI BETWEEN 1 AND 120),
 CONSTRAINT CK_ODR_TEH_REM CHECK (TEH_PODSETNIK_DANA BETWEEN 0 AND 365),
 CONSTRAINT CK_ODR_RAZ_REM CHECK (RAZ_PODSETNIK_DANA BETWEEN 0 AND 365),
 CONSTRAINT CK_ODR_VERSION CHECK (VERSION>0)
);
COMMENT ON COLUMN TED.UGO_ODRZAVANJE.TEH_PERIOD_MESECI IS 'NULL: custom periods to be entered in a later module';
