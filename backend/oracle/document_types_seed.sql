-- Run as TED if document tables exist but required document types are missing.
-- Repeatable: existing IDs and inactive types are preserved.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
MERGE INTO TED.UGO_TIP_DOC t
USING (
 SELECT 'UGOVOR' SIFRA, 'Ugovor' NAZIV, 10 REDOSLED FROM DUAL
 UNION ALL SELECT 'RESENJE', 'Rešenje za operativno praćenje', 20 FROM DUAL
 UNION ALL SELECT 'DODATNO_RESENJE', 'Dodatno rešenje', 30 FROM DUAL
 UNION ALL SELECT 'ZAPISNIK', 'Zapisnik', 40 FROM DUAL
) s ON (t.SIFRA = s.SIFRA)
WHEN NOT MATCHED THEN INSERT (SIFRA, NAZIV, STATUS, REDOSLED)
VALUES (s.SIFRA, s.NAZIV, 'A', s.REDOSLED);
COMMIT;
SELECT ID, SIFRA, NAZIV, STATUS FROM TED.UGO_TIP_DOC ORDER BY REDOSLED, ID;
