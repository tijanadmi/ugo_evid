-- Run once as TED, after access_roles.sql and document_deletion.sql.
-- Stop backend instances during migration. Oracle DDL commits automatically.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM user_tables WHERE table_name IN ('UGO_ROLA','UGO_DOC_BRISANJE');
 IF n<>2 THEN raise_application_error(-20001,'Apply access_roles.sql and document_deletion.sql first.'); END IF;
 SELECT COUNT(*) INTO n FROM (SELECT LOWER(TRIM(ad_sifra)) FROM TED.UGO_KOR GROUP BY LOWER(TRIM(ad_sifra)) HAVING COUNT(*)>1);
 IF n>0 THEN raise_application_error(-20002,'Duplicate AD usernames must be resolved before migration.'); END IF;
 SELECT COUNT(*) INTO n FROM user_tables WHERE table_name='PORTAL_ADMIN_LOCK';
 IF n>0 THEN raise_application_error(-20003,'Migration already started/applied; inspect its state.'); END IF;
END;
/
ALTER TABLE TED.UGO_ROLA DROP CONSTRAINT CK_UGO_ROLA_SIFRA;
ALTER TABLE TED.UGO_ROLA ADD CONSTRAINT CK_UGO_ROLA_SIFRA CHECK
 ((ID=1 AND SIFRA='GLE') OR (ID=2 AND SIFRA='IUD') OR (ID=3 AND SIFRA='ADM_KALENDAR') OR (ID=4 AND SIFRA='ADMIN'));
INSERT INTO TED.UGO_ROLA VALUES (4,'ADMIN','Administrator portala');
ALTER TABLE TED.UGO_KOR_ROLE DROP CONSTRAINT CK_KOR_ROLE_OPSEG;
ALTER TABLE TED.UGO_KOR_ROLE ADD CONSTRAINT CK_KOR_ROLE_OPSEG CHECK (
 (ID_UGO_ROLA IN (1,2) AND ((OPSEG='OJ' AND ID_UGO_ORG IS NOT NULL) OR (OPSEG='SVE_OJ' AND ID_UGO_ORG IS NULL)))
 OR (ID_UGO_ROLA IN (3,4) AND OPSEG='GLOBALNO' AND ID_UGO_ORG IS NULL));
ALTER TABLE TED.UGO_KOR ADD (VERSION NUMBER(19,0) DEFAULT 1 NOT NULL);
CREATE UNIQUE INDEX TED.UQ_UGO_KOR_AD_LOWER ON TED.UGO_KOR (LOWER(TRIM(AD_SIFRA)));

-- Serializes user/role writes across all servers, including last-admin checks.
CREATE TABLE TED.PORTAL_ADMIN_LOCK (ID NUMBER(1) PRIMARY KEY, CONSTRAINT CK_PORTAL_ADMIN_LOCK CHECK(ID=1));
INSERT INTO TED.PORTAL_ADMIN_LOCK VALUES (1);
CREATE TABLE TED.PORTAL_ADMIN_AUDIT (
 ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 ID_KORISNIKA NUMBER(19) NOT NULL,
