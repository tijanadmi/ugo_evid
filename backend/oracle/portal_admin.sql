CREATE INDEX TED.IX_PORTAL_ADMIN_AUDIT ON TED.PORTAL_ADMIN_AUDIT (VRSTA,ID_SLOGA,ID);

ALTER TABLE TED.UGO_DOC_BRISANJE ADD (
 BROJ_POKUSAJA NUMBER(19) DEFAULT 0 NOT NULL,
 POSLEDNJI_POKUSAJ TIMESTAMP,
 POSLEDNJA_GRESKA VARCHAR2(2000 BYTE)
);
CREATE TABLE TED.PORTAL_OBAVESTENJE (
 ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 IZVOR_KLJUC VARCHAR2(120 BYTE) NOT NULL UNIQUE,
 VRSTA VARCHAR2(40 BYTE) NOT NULL,
 ID_SLOGA NUMBER(19) NOT NULL,
 NASLOV VARCHAR2(300 CHAR) NOT NULL,
 PORUKA VARCHAR2(2000 BYTE),
 STATUS VARCHAR2(12 BYTE) DEFAULT 'OTVORENO' NOT NULL,
 ID_PREUZEO NUMBER(19),
 PRVI_PUT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 POSLEDNJI_PUT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 BROJ_PONAVLJANJA NUMBER(19) DEFAULT 1 NOT NULL,
 RESENO TIMESTAMP,
 VERSION NUMBER(19) DEFAULT 1 NOT NULL,
 CONSTRAINT CK_PORTAL_OBAV_STATUS CHECK(STATUS IN ('OTVORENO','PREUZETO','RESENO'))
