 VRSTA VARCHAR2(40 BYTE) NOT NULL,
 ID_SLOGA NUMBER(19) NOT NULL,
 PRE VARCHAR2(4000 BYTE),
 POSLE VARCHAR2(4000 BYTE),
 VREME TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
