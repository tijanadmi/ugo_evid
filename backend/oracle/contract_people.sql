-- Run once as TED with the backend stopped. Back up the schema first.
-- Existing UGO_EVID contact columns are retained as legacy data, not live SLM data.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM TED.UGO_EVID e
 JOIN TED.SAP_UGOVORI s ON s.id=e.id_sap_ugovor
 LEFT JOIN TED.UGO_DOB_LICA l ON l.id=e.id_ugo_dob_lica
 WHERE e.id_ugo_dob_lica IS NOT NULL
 AND (l.id IS NULL OR l.id_sap_dobavljac IS NULL OR s.id_sap_dobavljac IS NULL OR l.id_sap_dobavljac<>s.id_sap_dobavljac);
 IF n>0 THEN RAISE_APPLICATION_ERROR(-20001,'Existing SLM belongs to another supplier or is missing. Correct links before migration.'); END IF;
END;
/
CREATE TABLE TED.UGO_EVID_LICA (
 ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 ID_UGO_EVID INTEGER NOT NULL REFERENCES TED.UGO_EVID(ID),
 ID_UGO_DOB_LICA INTEGER NOT NULL REFERENCES TED.UGO_DOB_LICA(ID),
 ID_UGO_DOB_LICA_ROLA INTEGER NOT NULL REFERENCES TED.UGO_DOB_LICA_ROLE(ID),
 STATUS VARCHAR2(1 CHAR) DEFAULT 'A' NOT NULL CHECK (STATUS IN ('A','P')),
 VERSION NUMBER(19,0) DEFAULT 1 NOT NULL CHECK (VERSION>0),
 ID_KORISNIKA INTEGER,
 DATPRI TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 DATIZM TIMESTAMP
);
COMMENT ON COLUMN TED.UGO_EVID_LICA.ID_KORISNIKA IS 'NULL only for legacy import; application writes the acting user.';
CREATE UNIQUE INDEX TED.UQ_EVID_LICA_SLM_A ON TED.UGO_EVID_LICA (
 CASE WHEN STATUS='A' AND ID_UGO_DOB_LICA_ROLA=1 THEN ID_UGO_EVID END
);
CREATE UNIQUE INDEX TED.UQ_EVID_LICA_ACTIVE ON TED.UGO_EVID_LICA (
 CASE WHEN STATUS='A' THEN ID_UGO_EVID END,
 CASE WHEN STATUS='A' THEN ID_UGO_DOB_LICA END,
 CASE WHEN STATUS='A' THEN ID_UGO_DOB_LICA_ROLA END
);
CREATE INDEX TED.IX_EVID_LICA_CONTRACT ON TED.UGO_EVID_LICA(ID_UGO_EVID);
CREATE INDEX TED.IX_EVID_LICA_PERSON ON TED.UGO_EVID_LICA(ID_UGO_DOB_LICA);

-- Import only explicit SLM links. Do not guess technical teams from supplier contacts.
-- Preserve historical links even if the person has since left the supplier.
INSERT INTO TED.UGO_EVID_LICA(ID_UGO_EVID,ID_UGO_DOB_LICA,ID_UGO_DOB_LICA_ROLA,STATUS)
 SELECT ID,ID_UGO_DOB_LICA,1,'A' FROM TED.UGO_EVID WHERE ID_UGO_DOB_LICA IS NOT NULL;
COMMIT;

-- Remove the OLD per-supplier restriction only after successfully importing data.
DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER='TED' AND INDEX_NAME='UQ_UGO_DOB_LICA_SLM_A';
 IF n=1 THEN EXECUTE IMMEDIATE 'DROP INDEX TED.UQ_UGO_DOB_LICA_SLM_A'; END IF;
END;
/

