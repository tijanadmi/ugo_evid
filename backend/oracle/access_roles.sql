-- Run once as TED (SQL*Plus / SQLcl, or SQL Developer Run Script).
-- Back up UGO_KOR_ROLE first. Oracle DDL commits automatically.
-- Existing assignments retain their OJ and receive IUD (existing behavior).
-- Calendar administration is NOT assigned automatically.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name='UGO_ROLA';
  IF n>0 THEN raise_application_error(-20001,'UGO_ROLA already exists; migration was already started/applied.'); END IF;
  SELECT COUNT(*) INTO n FROM user_tab_columns
  WHERE table_name='UGO_KOR_ROLE' AND column_name IN ('ID_UGO_ROLA','OPSEG');
  IF n>0 THEN raise_application_error(-20002,'Role columns already exist. Check migration state.'); END IF;
END;
/

CREATE TABLE TED.UGO_ROLA (
 ID NUMBER(10,0) NOT NULL,
 SIFRA VARCHAR2(30 BYTE) NOT NULL,
 NAZIV VARCHAR2(150 CHAR) NOT NULL,
 CONSTRAINT PK_UGO_ROLA PRIMARY KEY(ID),
 CONSTRAINT UQ_UGO_ROLA_SIFRA UNIQUE(SIFRA),
 CONSTRAINT CK_UGO_ROLA_SIFRA CHECK
 ((ID=1 AND SIFRA='GLE') OR (ID=2 AND SIFRA='IUD') OR (ID=3 AND SIFRA='ADM_KALENDAR'))
);
INSERT INTO TED.UGO_ROLA VALUES (1,'GLE','Pregled');
INSERT INTO TED.UGO_ROLA VALUES (2,'IUD','Pregled, unos, izmena i brisanje');
INSERT INTO TED.UGO_ROLA VALUES (3,'ADM_KALENDAR','Administrator radnog kalendara');

ALTER TABLE TED.UGO_KOR_ROLE ADD (ID_UGO_ROLA NUMBER(10,0), OPSEG VARCHAR2(10 BYTE));
UPDATE TED.UGO_KOR_ROLE SET ID_UGO_ROLA=2, OPSEG='OJ';
ALTER TABLE TED.UGO_KOR_ROLE MODIFY (ID_UGO_ROLA NOT NULL, OPSEG NOT NULL, ID_UGO_ORG NULL);
ALTER TABLE TED.UGO_KOR_ROLE ADD CONSTRAINT FK_KOR_ROLE_ROLA FOREIGN KEY(ID_UGO_ROLA) REFERENCES TED.UGO_ROLA(ID);
ALTER TABLE TED.UGO_KOR_ROLE ADD CONSTRAINT CK_KOR_ROLE_OPSEG CHECK (
 (ID_UGO_ROLA IN (1,2) AND
   ((OPSEG='OJ' AND ID_UGO_ORG IS NOT NULL) OR (OPSEG='SVE_OJ' AND ID_UGO_ORG IS NULL)))
 OR (ID_UGO_ROLA=3 AND OPSEG='GLOBALNO' AND ID_UGO_ORG IS NULL)
);
-- Preserve any historical duplicate rows, but deactivate duplicate active grants.
UPDATE TED.UGO_KOR_ROLE SET STATUS='N', DATIZM=SYSDATE WHERE ID IN (
 SELECT ID FROM (SELECT ID, ROW_NUMBER() OVER (
 PARTITION BY ID_UGO_KOR,ID_UGO_ROLA,OPSEG,ID_UGO_ORG ORDER BY ID) rn
 FROM TED.UGO_KOR_ROLE WHERE STATUS='A') WHERE rn>1
);
CREATE UNIQUE INDEX TED.UQ_KOR_ROLE_ACTIVE ON TED.UGO_KOR_ROLE (
 CASE WHEN STATUS='A' THEN ID_UGO_KOR END,
 CASE WHEN STATUS='A' THEN ID_UGO_ROLA END,
 CASE WHEN STATUS='A' THEN OPSEG END,
 CASE WHEN STATUS='A' THEN NVL(ID_UGO_ORG,-1) END
);
COMMENT ON COLUMN TED.UGO_KOR_ROLE.OPSEG IS 'OJ: named organization; SVE_OJ: all organizations including future ones; GLOBALNO: calendar';
COMMIT;

