 SELECT 'RAZ_ZAHTEV' sifra, 'Zahtev za razvojnu podršku' naziv, 101 redosled FROM dual UNION ALL
 SELECT 'RAZ_DETALJI', 'Detalji razvojnog zahteva', 102 FROM dual UNION ALL
