CREATE TABLE TED.UGO_RADNI_KALENDAR (
 DATUM DATE PRIMARY KEY,
 RADNI CHAR(1) NOT NULL CHECK (RADNI IN ('D','N')),
 POTVRDJEN CHAR(1) DEFAULT 'N' NOT NULL CHECK (POTVRDJEN IN ('D','N')),
 OPIS VARCHAR2(200 CHAR),
 CONSTRAINT CK_RADNI_DATUM CHECK (DATUM=TRUNC(DATUM))
);
COMMENT ON TABLE TED.UGO_RADNI_KALENDAR IS 'Approved work calendar: every date, including weekends and holidays. Missing dates block deadline calculation.';

CREATE TABLE TED.UGO_TEH_PERIOD (
 ID NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 ID_ODRZAVANJA NUMBER(10,0) NOT NULL REFERENCES TED.UGO_ODRZAVANJE(ID),
 PERIOD_OD DATE NOT NULL, PERIOD_DO DATE NOT NULL,
 ID_TIP_DOC NUMBER(10,0) NOT NULL REFERENCES TED.UGO_TIP_DOC(ID),
 ROK_DOKUMENTA DATE, DATUM_POTPISA DATE,
 ID_UGO_DOC NUMBER(10,0) REFERENCES TED.UGO_DOC(ID),
 STATUS VARCHAR2(20 CHAR) DEFAULT 'PLANIRAN' NOT NULL,
 NAPOMENA VARCHAR2(2000 CHAR),
 VERSION NUMBER(19,0) DEFAULT 1 NOT NULL CHECK (VERSION>0),
 ID_KORISNIKA NUMBER(10,0) NOT NULL REFERENCES TED.UGO_KOR(ID),
 DATPRI TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, DATIZM TIMESTAMP,
 CONSTRAINT CK_TEH_DATUMI CHECK (PERIOD_OD=TRUNC(PERIOD_OD) AND PERIOD_DO=TRUNC(PERIOD_DO) AND PERIOD_OD<=PERIOD_DO),
 CONSTRAINT CK_TEH_STATUS CHECK (STATUS IN ('PLANIRAN','PRIPREMA','NA_POTPISU','ZAVRSEN','OTKAZAN')),
 CONSTRAINT CK_TEH_POTPIS CHECK (STATUS<>'ZAVRSEN' OR DATUM_POTPISA IS NOT NULL),
 CONSTRAINT UQ_TEH_PERIOD UNIQUE(ID_ODRZAVANJA,PERIOD_OD,PERIOD_DO)
);
CREATE INDEX TED.IX_TEH_PODSETNIK ON TED.UGO_TEH_PERIOD(STATUS,PERIOD_DO);

CREATE TABLE TED.UGO_RAZ_ZAHTEV (
 ID NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 ID_RAZ_FONDA NUMBER(10,0) NOT NULL REFERENCES TED.UGO_RAZ_FOND(ID),
 BROJ_ZAHTEVA VARCHAR2(100 CHAR) NOT NULL,
 DATUM_ZAHTEVA DATE NOT NULL,
 BROJ_CASOVA NUMBER(10,0) NOT NULL CHECK (BROJ_CASOVA BETWEEN 1 AND 2147483647),
 ROK_RADNIH_DANA NUMBER(5,0) NOT NULL CHECK (ROK_RADNIH_DANA BETWEEN 1 AND 3660),
 ROK_POTPISA DATE NOT NULL, DATUM_POTPISA DATE,
 ID_ZAHTEV_DOC NUMBER(10,0) REFERENCES TED.UGO_DOC(ID),
 ID_UGO_DOC NUMBER(10,0) REFERENCES TED.UGO_DOC(ID),
 STATUS VARCHAR2(20 CHAR) DEFAULT 'NACRT' NOT NULL,
 NAPOMENA VARCHAR2(2000 CHAR),
 VERSION NUMBER(19,0) DEFAULT 1 NOT NULL CHECK (VERSION>0),
 ID_KORISNIKA NUMBER(10,0) NOT NULL REFERENCES TED.UGO_KOR(ID),
 DATPRI TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, DATIZM TIMESTAMP,
 CONSTRAINT CK_RAZ_DATUMI CHECK (DATUM_ZAHTEVA=TRUNC(DATUM_ZAHTEVA) AND ROK_POTPISA>DATUM_ZAHTEVA),
 CONSTRAINT CK_RAZ_STATUS CHECK (STATUS IN ('NACRT','PODNET','U_RADU','NA_POTPISU','ZAVRSEN','OTKAZAN')),
 CONSTRAINT CK_RAZ_ROK_POTPISA CHECK (DATUM_POTPISA IS NULL OR (DATUM_POTPISA>=DATUM_ZAHTEVA AND DATUM_POTPISA<ROK_POTPISA)),
 CONSTRAINT CK_RAZ_POTPIS CHECK (STATUS<>'ZAVRSEN' OR DATUM_POTPISA IS NOT NULL)
);
CREATE INDEX TED.IX_RAZ_FOND_ZAHTEV ON TED.UGO_RAZ_ZAHTEV(ID_RAZ_FONDA,STATUS);
CREATE INDEX TED.IX_RAZ_PODSETNIK ON TED.UGO_RAZ_ZAHTEV(STATUS,ROK_POTPISA);
COMMENT ON COLUMN TED.UGO_RAZ_ZAHTEV.ROK_POTPISA IS 'Snapshot calculated using approved work calendar; counting starts the day after request date. Signature must be strictly before this date.';
COMMENT ON COLUMN TED.UGO_RAZ_ZAHTEV.STATUS IS 'NACRT/OTKAZAN do not consume hours; all other statuses reserve or consume hours.';
COMMIT;
